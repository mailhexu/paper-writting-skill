#!/usr/bin/env python3
"""Strict build gate (Story 014, FR-D3).

Deterministic submission-stage helper enforcing FR-D3 on a manuscript that
already has a Story-005 `evidence-manifest.yaml`:

  freeze  — pin the bibliography to a dated edition before drafting
            (bytes snapshot + sha256 + date in `bib-freeze.yaml`).
  build   — pre-checks, macro-file embedding, real pdflatex/bibtex run,
            citation-error extraction.

Failure semantics (no PDF is ever left behind that is claimed as a
successful build): a pinned artifact whose retrieved bytes do not match the
manifest sha256 fails naming the artifact and both hashes; undefined
citations or bibtex errors fail naming the citation keys; a bib that drifted
after its freeze point is never silently adopted (default: fail with an
explicit diff report; `--use-frozen` builds from the frozen bytes and prints
the same report).

Reuse, not duplication: schema validation, locator retrieval and sha256
verification come from `evidence_manifest.py` (Story 005/006/007); TeX
escaping and the generated-macro-file discipline follow `evidence_projection.py`
(Story 008, FR-D1: macros, never inline strings).

A green build certifies plumbing only — not scientific correctness, not
claim–evidence consistency, not language or figure quality. The gate never
runs scientific computation. Reproduction from a clean environment is
Story 015 (FR-D4), not this tool.

Usage:
    build_gate.py freeze <refs.bib> --record bib-freeze.yaml [--snapshot-dir bib-freeze]
    build_gate.py build --tex main.tex --manifest evidence-manifest.yaml
                        --bib refs.bib --freeze-record bib-freeze.yaml
                        --commit <40-hex sha> [--output-dir build] [--use-frozen]
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from evidence_manifest import HEX40, ManifestError, load_manifest, retrieve_bytes  # noqa: E402
from evidence_projection import tex_escape  # noqa: E402

try:
    import yaml
except ModuleNotFoundError:  # pragma: no cover - dependency notice
    sys.stderr.write("build-gate: error: PyYAML is required (pip install pyyaml)\n")
    raise SystemExit(2)

ERROR_PREFIX = "build-gate: error: "
FREEZE_SCHEMA = "pws.bib-freeze/1"
TEMPLATE_PATH = Path(__file__).resolve().parents[1] / "templates" / "build-info.tex.tmpl"
GENERATED_MARKER = "%% Generated by build_gate.py -- DO NOT EDIT"
CITATION_UNDEFINED = re.compile(r"Citation `([^']+)' on page \d+ undefined")
BIBTEX_MISSING_ENTRY = re.compile(r"I didn't find a database entry for `([^']+)'")
BIBTEX_ERROR = re.compile(r"BibTeX error|I was expecting|You're missing a field")


class BuildGateError(Exception):
    """Consumer-visible build-gate failure (exit 2)."""


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _fail(message: str) -> "BuildGateError":
    return BuildGateError(f"{ERROR_PREFIX}{message}")


# -- freeze -------------------------------------------------------------------


def freeze(bib_path: str, record_path: str, snapshot_dir: str) -> None:
    bib = Path(bib_path)
    try:
        payload = bib.read_bytes()
    except OSError as error:
        raise _fail(f"bib '{bib_path}': unreadable: {error}") from None
    digest = _sha256(payload)
    snaps = Path(snapshot_dir)
    if not snaps.is_absolute():
        snaps = Path(record_path).resolve().parent / snaps
    snapshot = snaps / f"{bib.stem}-{digest[:12]}.bib"
    try:
        snaps.mkdir(parents=True, exist_ok=True)
        if not snapshot.exists():
            snapshot.write_bytes(payload)
        elif snapshot.read_bytes() != payload:
            raise _fail(f"snapshot collision '{snapshot}': same name prefix, different bytes")
    except OSError as error:
        raise _fail(f"snapshot: cannot write '{snapshot}': {error}") from None
    record = {
        "schema": FREEZE_SCHEMA,
        "bib": str(bib),
        "sha256": digest,
        "frozen_at": date.today().isoformat(),
        "snapshot": str(snapshot),
    }
    existing = _load_freeze_record(record_path)
    if existing and existing["sha256"] == digest:
        _check_frozen_snapshot(existing, record_path)
        print(f"bib freeze: unchanged (sha256 {digest}, frozen at {existing['frozen_at']})")
        return
    try:
        Path(record_path).write_text(yaml.safe_dump(record, sort_keys=False), encoding="utf-8")
    except OSError as error:
        raise _fail(f"freeze record: cannot write '{record_path}': {error}") from None
    print(f"bib freeze: {bib_path} pinned at sha256 {digest} (snapshot {snapshot}, dated {record['frozen_at']})")


def _load_freeze_record(record_path: str) -> dict | None:
    path = Path(record_path)
    if not path.exists():
        return None
    try:
        record = yaml.safe_load(path.read_bytes().decode("utf-8"))
    except (OSError, yaml.YAMLError, UnicodeDecodeError) as error:
        raise _fail(f"freeze record '{record_path}': unreadable: {error}") from None
    if not isinstance(record, dict) or record.get("schema") != FREEZE_SCHEMA:
        raise _fail(f"freeze record '{record_path}': not a {FREEZE_SCHEMA} document")
    for field in ("sha256", "snapshot", "frozen_at"):
        if not isinstance(record.get(field), str) or not record[field].strip():
            raise _fail(f"freeze record '{record_path}': missing {field}")
    return record


def _check_frozen_snapshot(record: dict, record_path: str) -> bytes:
    snapshot = Path(record["snapshot"])
    try:
        frozen_bytes = snapshot.read_bytes()
    except OSError as error:
        raise _fail(
            f"freeze record '{record_path}': frozen snapshot '{snapshot}' unreadable ({error}); "
            f"re-run `freeze` to restore the dated edition"
        ) from None
    if _sha256(frozen_bytes) != record["sha256"]:
        raise _fail(
            f"freeze record '{record_path}': frozen snapshot '{snapshot}' bytes do not match "
            f"recorded sha256 {record['sha256']}; the dated edition is unrestorable, re-run `freeze`"
        )
    return frozen_bytes


# -- macro file (FR-D1: generated macro file, never inline strings) ------------


def render_build_info(commit: str, edition: str) -> str:
    template = TEMPLATE_PATH.read_text(encoding="utf-8")
    if GENERATED_MARKER not in template:
        raise _fail(f"template '{TEMPLATE_PATH}': missing generation marker")
    return template.replace("{BUILD_COMMIT}", tex_escape(commit)).replace(
        "{BUILD_EDITION}", tex_escape(edition)
    )


# -- pre-checks ----------------------------------------------------------------


def verify_pinned_inputs(manifest_path: str) -> str:
    """Retrieve every pinned artifact by its recorded locator and verify sha256."""
    document = load_manifest(manifest_path)  # ManifestError -> exit 2 with locator context
    base = Path(manifest_path).resolve().parent
    for artifact in document["artifacts"]:
        artifact_id = artifact["id"]
        payload = retrieve_bytes(artifact["locator"], artifact_id, base)
        actual = _sha256(payload)
        expected = artifact["sha256"]
        if actual != expected:
            raise _fail(
                f"pinned input '{artifact_id}': sha256 mismatch: expected {expected}, "
                f"actual {actual} (locator {artifact['locator']}); "
                f"the adopted edition is not what would be built"
            )
        print(f"pinned input '{artifact_id}': sha256 verified ({expected[:12]}…)")
    return document["edition"]


def resolve_bib(bib_path: str, freeze_record_path: str, use_frozen: bool) -> tuple[bytes, str]:
    """Return the bib bytes the build may use and a human-readable freeze report.

    A drifted bib is never silently adopted: default is fail-with-report;
    --use-frozen builds from the frozen snapshot and still prints the report.
    """
    record = _load_freeze_record(freeze_record_path)
    if record is None:
        raise _fail(
            f"freeze record '{freeze_record_path}': missing; run `build_gate.py freeze` "
            f"before drafting — bibliography resolution must be frozen to a dated edition"
        )
    bib = Path(bib_path)
    try:
        current = bib.read_bytes()
    except OSError as error:
        raise _fail(f"bib '{bib_path}': unreadable: {error}") from None
    frozen_sha = record["sha256"]
    if _sha256(current) == frozen_sha:
        return current, f"bib freeze: verified {bib_path} == frozen edition (sha256 {frozen_sha})"
    report = (
        f"bib freeze: DRIFT — {bib_path} changed after the freeze point "
        f"(frozen {record['frozen_at']}, sha256 {frozen_sha}; current sha256 {_sha256(current)}); "
        f"the frozen edition governs this build, new bytes are NOT adopted"
    )
    frozen_bytes = _check_frozen_snapshot(record, freeze_record_path)
    if not use_frozen:
        raise _fail(
            f"{report}; re-run `freeze` to adopt a new dated edition explicitly "
            f"(or build --use-frozen to build from the frozen edition)"
        )
    print(report)
    return frozen_bytes, report


# -- compile + citation extraction ---------------------------------------------


def citation_errors(log_text: str, blg_text: str | None) -> list[str]:
    keys: list[str] = []
    for match in CITATION_UNDEFINED.finditer(log_text):
        if match.group(1) not in keys:
            keys.append(match.group(1))
    if "There were undefined references." in log_text and not keys:
        keys.append("<undefined references reported by LaTeX>")
    if blg_text is not None:
        for match in BIBTEX_MISSING_ENTRY.finditer(blg_text):
            if match.group(1) not in keys:
                keys.append(match.group(1))
        if BIBTEX_ERROR.search(blg_text) and not keys:
            keys.append("<bibtex error reported>")
    return keys


def _aux_bibliography(aux_path: Path) -> list[str]:
    """Return the bibliography base names the first TeX pass requested (\\bibdata)."""
    try:
        text = aux_path.read_text(encoding="utf-8", errors="replace")
    except OSError as error:
        raise _fail(f"aux '{aux_path}': unreadable: {error}") from None
    names: list[str] = []
    for match in re.finditer(r"\\bibdata\{([^}]*)\}", text):
        names.extend(part.strip() for part in match.group(1).split(",") if part.strip())
    return names


def _run(command: list[str], cwd: Path, env: dict[str, str] | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(
        command, cwd=cwd, env=env, capture_output=True, text=True, timeout=600
    )


def build(
    tex_path: str,
    manifest_path: str,
    bib_path: str,
    freeze_record_path: str,
    commit: str,
    output_dir: str,
    use_frozen: bool,
) -> None:
    if not HEX40.fullmatch(commit or ""):
        raise _fail(f"--commit '{commit}': must be the 40-hex commit SHA embedded in the build")
    tex = Path(tex_path)
    if not tex.is_file():
        raise _fail(f"--tex '{tex_path}': does not exist")
    out = Path(output_dir).resolve()
    if out.exists():
        raise _fail(f"--output-dir '{out}': already exists; the gate writes a fresh build tree")

    # 1. pinned inputs: recorded locator -> actual bytes -> sha256 (no HEAD surrogate)
    edition = verify_pinned_inputs(manifest_path)

    # 2. bibliography: frozen dated edition governs; drift is loud, never silent
    bib_bytes, _report = resolve_bib(bib_path, freeze_record_path, use_frozen)

    # 3. embed commit SHA + evidence edition via the generated macro file
    out.mkdir(parents=True)
    build_info = out / "build-info.tex"
    build_info.write_text(render_build_info(commit, edition), encoding="utf-8")
    bib_in_build = out / Path(bib_path).name
    bib_in_build.write_bytes(bib_bytes)

    def abort_from_log(stage: str, exit_code: int) -> None:
        # citation keys take precedence over a bare exit status in the report
        log_path = out / f"{tex.stem}.log"
        log_text = log_path.read_text(encoding="utf-8", errors="replace") if log_path.exists() else ""
        keys = citation_errors(log_text, None)
        detail = (
            "citation errors: unresolved citation key(s) " + ", ".join(f"'{k}'" for k in keys)
            if keys
            else f"{stage} exited {exit_code}"
        )
        _abort(out, f"{detail}; no PDF is emitted as a successful build")

    try:
        # 4. real TeX run against the manuscript directory (build dir supplies generated files)
        tex_env = {**os.environ, "TEXINPUTS": f"{out}:"}
        tex_result = _run(
            ["pdflatex", "-interaction=nonstopmode", f"-output-directory={out}", tex.name],
            cwd=tex.parent,
            env=tex_env,
        )
        if tex_result.returncode != 0:
            abort_from_log("pdflatex", tex_result.returncode)
        aux = out / f"{tex.stem}.aux"
        bibdata = _aux_bibliography(aux)
        expected_stem = Path(bib_path).stem
        if bibdata != [expected_stem]:
            _abort(
                out,
                f"manuscript requests bibliography {bibdata} but the frozen input is "
                f"'{expected_stem}'; the gate builds only against the frozen edition "
                f"(pass the frozen file as --bib, or freeze the requested file)",
            )
        bibtex_result = _run(
            ["bibtex", f"{tex.stem}.aux"],
            cwd=out,
            env={**os.environ, "BIBINPUTS": f"{out}:"},
        )
        for index in range(2):
            rerun = _run(
                ["pdflatex", "-interaction=nonstopmode", f"-output-directory={out}", tex.name],
                cwd=tex.parent,
                env=tex_env,
            )
            if rerun.returncode != 0:
                abort_from_log(f"pdflatex (post-bibtex pass {index + 1})", rerun.returncode)
        blg_path = out / f"{tex.stem}.blg"
        log_path = out / f"{tex.stem}.log"
        log_text = log_path.read_text(encoding="utf-8", errors="replace") if log_path.exists() else ""
        blg_text = blg_path.read_text(encoding="utf-8", errors="replace") if blg_path.exists() else None

        # 5. citation errors fail the build, naming the keys (Manubot-tolerance anti-pattern)
        keys = citation_errors(log_text, blg_text)
        if keys:
            _abort(out, "citation errors: unresolved citation key(s) " + ", ".join(f"'{k}'" for k in keys))
        if bibtex_result.returncode != 0:
            _abort(out, f"bibtex exited {bibtex_result.returncode}")

        pdf = out / f"{tex.stem}.pdf"
        if not pdf.is_file():
            _abort(out, "pdflatex reported success but no PDF was produced")

        # 6. green requires the rendered PDF to actually carry the provenance macros
        rendered = _run(["pdftotext", str(pdf), "-"], cwd=out)
        if rendered.returncode != 0:
            _abort(out, f"pdftotext exited {rendered.returncode}; provenance embedding could not be verified")
        missing = [
            label
            for label, value in (("commit SHA", commit), ("evidence edition", edition))
            if value not in rendered.stdout
        ]
        if missing:
            _abort(
                out,
                f"rendered PDF does not contain the { ' and '.join(missing) }; "
                f"the manuscript must use the generated \\buildcommit/\\buildedition macros "
                f"(\\input{{build-info.tex}}) so provenance is embedded, not omitted",
            )
        version_result = _run(["pdflatex", "--version"], cwd=out)
        version = version_result.stdout.splitlines()[0] if version_result.returncode == 0 and version_result.stdout.splitlines() else ""
        if not version:
            _abort(
                out,
                f"pdflatex --version failed or returned nothing (exit {version_result.returncode}); "
                f"no PDF is emitted as a successful build",
            )
    except (OSError, subprocess.TimeoutExpired) as error:
        _abort(out, f"TeX toolchain failure: {type(error).__name__}: {error}")

    print(
        f"build gate: PASS — commit {commit}, evidence edition '{edition}', "
        f"pdf {pdf} ({pdf.stat().st_size} bytes), {version}"
    )
    print("build gate: green certifies plumbing only; claim–evidence consistency sits above this gate")


def _abort(out: Path, message: str) -> None:
    for produced in out.glob("*.pdf"):
        produced.unlink()
    raise _fail(f"{message}; removed every PDF under '{out}' so none is mistaken for a successful build")


# -- CLI -----------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="build-gate", description="Strict build gate (FR-D3)")
    commands = parser.add_subparsers(dest="command", required=True)

    freeze_parser = commands.add_parser("freeze", help="pin the bibliography to a dated edition")
    freeze_parser.add_argument("bib")
    freeze_parser.add_argument("--record", required=True)
    freeze_parser.add_argument("--snapshot-dir", default="bib-freeze")

    build_parser = commands.add_parser("build", help="gated clean build")
    build_parser.add_argument("--tex", required=True)
    build_parser.add_argument("--manifest", required=True)
    build_parser.add_argument("--bib", required=True)
    build_parser.add_argument("--freeze-record", required=True)
    build_parser.add_argument("--commit", required=True)
    build_parser.add_argument("--output-dir", default="build")
    build_parser.add_argument("--use-frozen", action="store_true")

    arguments = parser.parse_args(argv)
    try:
        if arguments.command == "freeze":
            freeze(arguments.bib, arguments.record, arguments.snapshot_dir)
        elif arguments.command == "build":
            build(
                arguments.tex,
                arguments.manifest,
                arguments.bib,
                arguments.freeze_record,
                arguments.commit,
                arguments.output_dir,
                arguments.use_frozen,
            )
    except (BuildGateError, ManifestError) as error:
        sys.stderr.write(f"{error}\n")
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
