#!/usr/bin/env python3
r"""Evidence metadata TeX projection generator (Story 008, FR-D5 / ADR-005 / STD-005).

Reads an adopted evidence manifest and draft ``\evidenceblock{ID}`` calls.
Generates short gray notes: claim/artifact ID, edition, linked filenames and
SHA-12. Full intent, source sets, locators, commits and hashes remain in the
manifest and non-rendered JSON comments in the generated file.

The single ``\evidencemarginfalse`` toggle hides notes in the PDF only.
Clean source export removes the private metadata entirely (Story 009).

The generated file is NOT hand-edited: regeneration overwrites it in full.

ID charset (restricted ASCII, FR-D5/STD-005): letters, digits, hyphens only.
Field values with `_ % # & $ ~ ^ \ { }` and spaces are escaped, never rejected.

No language polish, no word counting, no adoption logic — projection only.

Usage:
    evidence_projection.py generate <manifest.yaml> --tex draft.tex --output evidence-metadata.tex
    evidence_projection.py validate-id <proposed-id>
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

try:
    import yaml
except ModuleNotFoundError:  # pragma: no cover - dependency notice
    sys.stderr.write("evidence-projection: error: PyYAML is required (pip install pyyaml)\n")
    raise SystemExit(2)

ERROR_PREFIX = "evidence-projection: error: "
ID_PATTERN = re.compile(r"[A-Za-z0-9-]+")
HEX64 = re.compile(r"[0-9a-f]{64}")
HEX40 = re.compile(r"[0-9a-f]{40}")
LOCATOR_KINDS = ("git", "snapshot", "retained")
EVIDENCEBLOCK_CALL = re.compile(r"\\evidenceblock\s*\{([^{}]*)\}")
TEMPLATE_PATH = Path(__file__).resolve().parents[1] / "templates" / "evidence-metadata.tex.tmpl"
GENERATED_MARKER = "%% Generated by evidence_projection.py -- DO NOT EDIT"


class ProjectionError(Exception):
    """Consumer-visible generation or validation failure (exit 2)."""


# -- ID charset ---------------------------------------------------------------


def validate_id(proposed: str, location: str) -> str:
    if not isinstance(proposed, str) or not proposed:
        raise ProjectionError(f"{location}: id is empty; expected restricted ASCII letters/digits/hyphens")
    if not ID_PATTERN.fullmatch(proposed):
        raise ProjectionError(
            f"{location}: id '{proposed}' is not restricted ASCII (letters, digits, hyphens only); "
            f"free text belongs in manifest fields, not the id"
        )
    return proposed


# -- escaping (rendering must round-trip the field text) ----------------------

_ESCAPES = (
    ("\\", "\\textbackslash{}"),
    ("{", "\\{"),
    ("}", "\\}"),
    ("$", "\\$"),
    ("&", "\\&"),
    ("%", "\\%"),
    ("#", "\\#"),
    ("_", "\\_"),
    ("^", "\\textasciicircum{}"),
    ("~", "\\textasciitilde{}"),
    (" ", "\\ "),  # explicit interword glue: runs of spaces survive rendering
)
_ESCAPE_MAP = dict(_ESCAPES)
_ESCAPE_SCAN = re.compile("|".join(re.escape(char) for char, _ in _ESCAPES))


def tex_escape(value: str) -> str:
    """Single-pass escape: earlier replacements are never re-scanned."""
    return _ESCAPE_SCAN.sub(lambda match: _ESCAPE_MAP[match.group(0)], value)


# -- light manifest loading (Story-005 schema, self-contained) ----------------


def load_manifest(manifest_path: str) -> dict:
    path = Path(manifest_path)
    try:
        raw = path.read_bytes()
    except OSError as error:
        raise ProjectionError(f"manifest: unreadable: {error}") from error
    try:
        document = yaml.safe_load(raw.decode("utf-8"))
    except (yaml.YAMLError, UnicodeDecodeError) as error:
        raise ProjectionError(f"manifest: invalid YAML: {error}") from error
    if not isinstance(document, dict):
        raise ProjectionError("manifest: top level must be a mapping")
    return document


def validate_manifest(document: dict) -> tuple[dict[str, dict], dict[str, dict]]:
    if not isinstance(document.get("edition"), str) or not document["edition"].strip():
        raise ProjectionError("manifest.edition: missing or empty")
    artifacts = document.get("artifacts")
    if not isinstance(artifacts, list) or not artifacts:
        raise ProjectionError("manifest.artifacts: missing or empty")
    artifact_map: dict[str, dict] = {}
    for index, artifact in enumerate(artifacts):
        location = f"manifest.artifacts[{index}]"
        if not isinstance(artifact, dict):
            raise ProjectionError(f"{location}: entry must be a mapping")
        artifact_id = validate_id(artifact.get("id"), f"{location}.id")
        if artifact_id in artifact_map:
            raise ProjectionError(f"{location}.id: duplicate artifact id '{artifact_id}'")
        digest = artifact.get("sha256")
        if not isinstance(digest, str) or not HEX64.fullmatch(digest):
            raise ProjectionError(f"{location}.sha256: must be 64 lowercase hex characters")
        locator = artifact.get("locator")
        if not isinstance(locator, dict):
            raise ProjectionError(f"{location}.locator: missing; a hash is a fingerprint, not a retrieval method")
        kind = locator.get("kind")
        if kind not in LOCATOR_KINDS:
            raise ProjectionError(f"{location}.locator.kind: must be one of {' / '.join(LOCATOR_KINDS)}")
        if kind == "git":
            for field in ("repo", "commit", "path"):
                if not isinstance(locator.get(field), str) or not locator[field].strip():
                    raise ProjectionError(f"{location}.locator.{field}: missing for git locator")
            if not HEX40.fullmatch(locator["commit"]):
                raise ProjectionError(f"{location}.locator.commit: must be the full 40-hex commit SHA")
        elif not isinstance(locator.get("path"), str) or not locator["path"].strip():
            raise ProjectionError(f"{location}.locator.path: missing for {kind} locator")
        artifact_map[artifact_id] = artifact

    claims = document.get("claims")
    if not isinstance(claims, list) or not claims:
        raise ProjectionError("manifest.claims: missing or empty")
    claim_map: dict[str, dict] = {}
    for index, claim in enumerate(claims):
        location = f"manifest.claims[{index}]"
        if not isinstance(claim, dict):
            raise ProjectionError(f"{location}: entry must be a mapping")
        claim_id = validate_id(claim.get("id"), f"{location}.id")
        if claim_id in claim_map:
            raise ProjectionError(f"{location}.id: duplicate claim id '{claim_id}'")
        for field in ("statement", "intent", "reason"):
            if not isinstance(claim.get(field), str) or not claim[field].strip():
                raise ProjectionError(f"{location}.{field}: missing or empty")
        references = claim.get("artifacts")
        if not isinstance(references, list) or not references:
            raise ProjectionError(f"{location}.artifacts: missing or empty")
        for reference in references:
            if not isinstance(reference, str) or reference not in artifact_map:
                raise ProjectionError(f"{location}.artifacts: unknown artifact id '{reference}'")
        display = claim.get("display_artifact")
        if "display_artifact" in claim and (
            not isinstance(display, str) or display not in references
        ):
            raise ProjectionError(f"{location}.display_artifact: must name one of the claim's artifacts")
        claim_map[claim_id] = claim
    return artifact_map, claim_map


# -- projection ---------------------------------------------------------------


def _strip_tex_comments(text: str) -> str:
    """Drop TeX comments: an unescaped % comments out the rest of its line."""
    out: list[str] = []
    for line in text.splitlines(keepends=True):
        body, newline = line, ""
        while body and body[-1] in "\r\n":
            newline = body[-1] + newline
            body = body[:-1]
        kept: list[str] = []
        index = 0
        while index < len(body):
            char = body[index]
            if char == "\\":
                kept.append(body[index : index + 2])  # escape pair (\% is not a comment marker)
                index += 2
                continue
            if char == "%":
                break  # comment: rest of the line is inert for TeX
            kept.append(char)
            index += 1
        out.append("".join(kept) + newline)
    return "".join(out)


def scan_draft_calls(draft_path: str, known_ids: set[str]) -> list[str]:
    try:
        text = Path(draft_path).read_text(encoding="utf-8")
    except OSError as error:
        raise ProjectionError(f"--tex: unreadable: {error}") from error
    referenced: list[str] = []
    for match in EVIDENCEBLOCK_CALL.finditer(_strip_tex_comments(text)):
        proposed = match.group(1).strip()
        try:
            artifact_id = validate_id(proposed, "draft \\evidenceblock argument")
        except ProjectionError:
            raise ProjectionError(
                f"draft \\evidenceblock{{ '{proposed}' }}: id is not restricted ASCII "
                f"(letters, digits, hyphens only); free text must live in manifest fields"
            ) from None
        if artifact_id not in known_ids:
            known = ", ".join(sorted(known_ids))
            raise ProjectionError(
                f"draft \\evidenceblock{{{artifact_id}}}: id not in manifest (known ids: {known}); "
                f"regenerate after the manifest registers the adopted evidence"
            )
        if artifact_id not in referenced:
            referenced.append(artifact_id)
    return referenced


def build_entries(
    draft_path: str, edition: str, artifact_map: dict, claim_map: dict, manifest: Path
) -> str:
    """Render compact notes; retain the complete source mapping out of view."""
    used = scan_draft_calls(draft_path, set(artifact_map) | set(claim_map))
    lines: list[str] = []
    for entry_id in used:
        claim = claim_map.get(entry_id)
        sources = claim["artifacts"] if claim else [entry_id]
        visible = claim.get("display_artifact", sources[0]) if claim else entry_id
        metadata = {
            "id": entry_id,
            "edition": edition,
            "claim": {key: claim[key] for key in ("id", "statement", "intent", "reason", "artifacts")} if claim else None,
            "artifacts": {
                source: {
                    "sha256": artifact_map[source]["sha256"],
                    "locator": {
                        key: artifact_map[source]["locator"][key]
                        for key in (("kind", "repo", "commit", "path")
                                    if artifact_map[source]["locator"]["kind"] == "git"
                                    else ("kind", "path"))
                    },
                }
                for source in sources
            },
        }
        lines.append("%% evidence " + json.dumps(metadata, sort_keys=True, ensure_ascii=True))
        parts = [f"[evidence] {tex_escape(entry_id)}", tex_escape(edition)]
        parts.append(_artifact_link(artifact_map[visible], manifest))
        extra = len(metadata["artifacts"]) - 1
        if extra:
            parts.append(_file_link(manifest, f"+{extra} sources"))
        entry = " \\textperiodcentered{} ".join(parts)
        lines.append("\\expandafter\\def\\csname evdblock@" + entry_id + "\\endcsname{" + entry + "}")
    return "\n".join(lines) + "\n"


def _artifact_link(artifact: dict, manifest: Path) -> str:
    locator = artifact["locator"]
    path = manifest if locator["kind"] == "git" else manifest.parent / locator["path"]
    label = Path(locator["path"]).name
    if locator["kind"] == "git":
        label += " (locator)"
    return _file_link(path, label) + " \\texttt{" + artifact["sha256"][:12] + "}"


def _file_link(path: Path, label: str) -> str:
    # A true URI avoids hyperref's remote-PDF and extensionless-file rewriting.
    uri = path.absolute().as_uri().replace("~", "%7E").replace("_", "%5F")
    return "\\evidenceuri{" + tex_escape(uri) + "}{" + tex_escape(label) + "}"


def generate(manifest_path: str, draft_path: str, output: str | None, template: Path) -> None:
    document = load_manifest(manifest_path)
    artifact_map, claim_map = validate_manifest(document)
    entries = build_entries(draft_path, document["edition"], artifact_map, claim_map, Path(manifest_path).resolve())
    try:
        skeleton = template.read_text(encoding="utf-8")
    except OSError as error:
        raise ProjectionError(f"template: unreadable: {error}") from error
    rendered = skeleton.replace("{EVD_ENTRIES}", entries.rstrip("\n"))
    if not rendered.startswith(GENERATED_MARKER):
        raise ProjectionError(
            f"template '{template}': missing generated marker header; refusing to emit unmarked projection"
        )
    rendered += "\n"  # deterministic trailing newline
    destination = None if output == "-" else Path(output)
    if destination is not None:
        try:
            if destination.exists() and destination.read_text(encoding="utf-8", errors="replace") != rendered:
                print(
                    f"notice: '{destination}' already existed with different content; "
                    f"regenerated in full — hand edits to the projection are overwritten by design"
                )
            destination.write_text(rendered, encoding="utf-8")
        except OSError as error:
            raise ProjectionError(f"--output: cannot write '{destination}': {error}") from error
        print(f"evidence-metadata written to {destination} ({len(rendered)} bytes)")
    else:
        sys.stdout.write(rendered)


def validate_id_command(proposed: str) -> None:
    validate_id(proposed, "validate-id")
    print(f"id '{proposed}': valid (restricted ASCII letters/digits/hyphens)")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="evidence_projection.py",
        description=__doc__.splitlines()[0],
        epilog="The generated evidence-metadata.tex is regenerated in full on every run; hand edits are overwritten by design.",
    )
    commands = parser.add_subparsers(dest="command", required=True)
    generate_parser = commands.add_parser("generate", help="generate evidence-metadata.tex from manifest + draft")
    generate_parser.add_argument("manifest")
    generate_parser.add_argument("--tex", required=True, help="draft .tex whose \\evidenceblock{ID} calls to project")
    generate_parser.add_argument("--output", default="evidence-metadata.tex")
    generate_parser.add_argument("--template", default=str(TEMPLATE_PATH))
    id_parser = commands.add_parser("validate-id", help="check an id against the restricted ASCII charset")
    id_parser.add_argument("proposed_id")
    arguments = parser.parse_args(argv)
    try:
        if arguments.command == "generate":
            generate(arguments.manifest, arguments.tex, arguments.output, Path(arguments.template))
        else:
            validate_id_command(arguments.proposed_id)
    except ProjectionError as error:
        sys.stderr.write(ERROR_PREFIX + str(error) + "\n")
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
