"""Story 009: clean source export and leak check (real pdflatex smoke included)."""

from __future__ import annotations

import hashlib
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

TOOLS = Path(__file__).resolve().parents[1] / "paper-writing-skill" / "tools"
sys.path.insert(0, str(TOOLS))

import evidence_export as ee  # noqa: E402

PYTHON = sys.executable
TOOL = str(TOOLS / "evidence_export.py")

PREAMBLE = """\\documentclass{article}
\\input{evidence-metadata.tex}
\\begin{document}
"""

DRAFT = (
    PREAMBLE
    + """Magnon lifetimes agree within five percent.
\\evidenceblock{tb2j-run-42}
Data availability: all runs are archived (public statement, kept byte-for-byte).
\\end{document}
"""
)

METADATA = "%% Generated by evidence_projection.py -- DO NOT EDIT\n\\evidencemargintrue\n"

SUB_FILE = "\\section{Methods}\nSubsection body text preserved verbatim.\n"

DRAFT_WITH_INPUT = (
    PREAMBLE
    + "Magnon lifetimes agree within five percent.\n"
    + "\\input{methods}\n\\evidenceblock{tb2j-run-42}\n"
    + "Data availability: all runs are archived (public statement, kept byte-for-byte).\n\\end{document}\n"
)


def make_project(tmp_path: Path) -> Path:
    (tmp_path / "draft.tex").write_text(DRAFT, encoding="utf-8")
    (tmp_path / "evidence-metadata.tex").write_text(METADATA, encoding="utf-8")
    return tmp_path


def run_cli(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run([PYTHON, TOOL, *args], capture_output=True, text=True, timeout=300)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def tree_digests(root: Path) -> dict[str, str]:
    return {
        str(p.relative_to(root)): digest(p) for p in sorted(root.rglob("*")) if p.is_file()
    }


# -- strip unit behavior -------------------------------------------------------


def test_strip_removes_only_metadata_lines():
    text = DRAFT + "% \\evidenceblock{commented}\n"
    stripped = ee.strip_tex(text, "evidence-metadata.tex", "draft.tex")
    assert "\\evidenceblock" not in stripped
    assert "\\input{evidence-metadata.tex}" not in stripped
    assert "Data availability: all runs are archived (public statement, kept byte-for-byte)." in stripped
    assert "Magnon lifetimes agree within five percent." in stripped


def test_strip_refuses_verbatim_calls():
    text = DRAFT.replace("\\end{document}", "\\begin{verbatim}\n\\evidenceblock{x}\n\\end{verbatim}\n\\end{document}")
    with pytest.raises(ee.ExportError, match="verbatim"):
        ee.strip_tex(text, "evidence-metadata.tex", "draft.tex")


def test_local_inputs_stay_inside_root(tmp_path):
    (tmp_path / "methods.tex").write_text(SUB_FILE, encoding="utf-8")
    (tmp_path / ".." / "outside.tex").write_text("x", encoding="utf-8")
    assert (tmp_path / "methods.tex") in ee._local_inputs("\\input{methods}", tmp_path, "draft.tex")
    with pytest.raises(ee.ExportError, match="outside the manuscript directory"):
        ee._local_inputs("\\input{../outside}", tmp_path, "draft.tex")


# -- export end to end ---------------------------------------------------------


@pytest.fixture(scope="module")
def exported(tmp_path_factory):
    source = tmp_path_factory.mktemp("work")
    make_project(source)
    (source / "draft.tex").write_text(DRAFT_WITH_INPUT, encoding="utf-8")
    (source / "methods.tex").write_text(SUB_FILE, encoding="utf-8")
    (source / "refs.bib").write_text("@article{k, title={Keep me}}\n", encoding="utf-8")
    before = tree_digests(source)

    out = tmp_path_factory.mktemp("exports") / "clean"
    result = run_cli(
        "export", str(source / "draft.tex"), "--output-dir", str(out),
        "--copy", "refs.bib",
    )
    assert result.returncode == 0, result.stderr
    return {"source": source, "before": before, "out": out, "message": result.stdout}


def test_export_strips_evidence_and_preserves_public(exported):
    out = exported["out"]
    draft = (out / "draft.tex").read_text(encoding="utf-8")
    assert "\\evidenceblock" not in draft
    assert "\\input{evidence-metadata.tex}" not in draft
    assert not (out / "evidence-metadata.tex").exists()
    assert "Data availability: all runs are archived (public statement, kept byte-for-byte)." in draft
    assert "Magnon lifetimes agree within five percent." in draft
    assert (out / "methods.tex").read_text(encoding="utf-8") == SUB_FILE  # byte-for-byte
    assert digest(out / "refs.bib") == digest(exported["source"] / "refs.bib")
    assert (out / "draft.pdf").is_file()  # standalone compile produced a PDF


def test_export_leak_check_passes_and_working_copy_untouched(exported):
    result = run_cli("leak-check", str(exported["out"]))
    assert result.returncode == 0, result.stderr
    assert tree_digests(exported["source"]) == exported["before"]  # working copy byte-identical


def test_leak_check_fails_on_deliberate_residue(tmp_path_factory):
    dirty = tmp_path_factory.mktemp("dirty") / "residue"
    dirty.mkdir(parents=True)
    (dirty / "main.tex").write_text("Some text\n\\evidenceblock{tb2j-run-42}\n", encoding="utf-8")
    result = run_cli("leak-check", str(dirty))
    assert result.returncode == 2
    assert "main.tex:2" in result.stderr  # location reported


def test_export_refuses_existing_output_dir(tmp_path):
    make_project(tmp_path)
    (tmp_path / "exists").mkdir()
    result = run_cli("export", str(tmp_path / "draft.tex"), "--output-dir", str(tmp_path / "exists"))
    assert result.returncode == 2
    assert "already exists" in result.stderr


def test_plain_manuscript_exports_equivalent(tmp_path_factory):
    plain = tmp_path_factory.mktemp("plain")
    (plain / "main.tex").write_text(
        "\\documentclass{article}\n\\begin{document}\nPlain body, no evidence constructs.\n\\end{document}\n",
        encoding="utf-8",
    )
    out = tmp_path_factory.mktemp("plain-out") / "clean"
    result = run_cli("export", str(plain / "main.tex"), "--output-dir", str(out))
    assert result.returncode == 0, result.stderr
    assert (out / "main.tex").read_text(encoding="utf-8") == (plain / "main.tex").read_text(encoding="utf-8")
    assert run_cli("leak-check", str(out)).returncode == 0


def test_crlf_line_endings_survive_export(tmp_path_factory):
    source = tmp_path_factory.mktemp("crlf") / "work"
    source.mkdir(parents=True)
    (source / "draft.tex").write_bytes(
        b"\\documentclass{article}\r\n\\input{evidence-metadata.tex}\r\n\\begin{document}\r\n"
        b"Body line kept exactly.\r\n\\evidenceblock{run-42}\r\n"
        b"Data availability: archived.\r\n\\end{document}\r\n"
    )
    (source / "evidence-metadata.tex").write_bytes(b"%% generated\r\n\\evidencemargintrue\r\n")
    out = tmp_path_factory.mktemp("crlf-out") / "clean"
    result = run_cli("export", str(source / "draft.tex"), "--output-dir", str(out), "--no-compile")
    assert result.returncode == 0, result.stderr
    exported = (out / "draft.tex").read_bytes()
    assert b"\\input{evidence-metadata.tex}" not in exported
    assert b"Body line kept exactly.\r\n" in exported  # CRLF preserved, no normalization
    assert b"Data availability: archived.\r\n\\end{document}\r\n" in exported


