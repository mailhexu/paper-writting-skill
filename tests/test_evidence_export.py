def test_outside_input_rejected_flat_and_nested(tmp_path_factory):
    flat = tmp_path_factory.mktemp("flat")
    make_project(flat)
    (flat.parent / "outside.tex").write_text("secret body", encoding="utf-8")
    (flat / "draft.tex").write_text(DRAFT + "\\input{../outside}\n\\end{document}\n", encoding="utf-8")
    result = run_cli("export", str(flat / "draft.tex"), "--output-dir", str(flat.parent / "flat-out"), "--no-compile")
    assert result.returncode == 2
    assert "outside the manuscript directory" in result.stderr

    nested_root = tmp_path_factory.mktemp("nested")
    sub = nested_root / "sub"
    sub.mkdir()
    (nested_root / "outside.tex").write_text("secret body", encoding="utf-8")
    (sub / "main.tex").write_text(
        "\\documentclass{article}\n\\begin{document}\n\\input{../outside}\n\\end{document}\n",
        encoding="utf-8",
    )
    result = run_cli("export", str(sub / "main.tex"), "--output-dir", str(nested_root / "nested-out"), "--no-compile")
    assert result.returncode == 2
    assert "outside the manuscript directory" in result.stderr


def test_private_marker_leak_detected(tmp_path_factory):
    source = tmp_path_factory.mktemp("marker") / "work"
    source.mkdir(parents=True)
    (source / "draft.tex").write_text(
        "\\documentclass{article}\n\\begin{document}\nBody.\n\\end{document}\n", encoding="utf-8"
    )
    (source / "notes.txt").write_text("cached from /home/hexu/private-dataset/run9\n", encoding="utf-8")
    out = tmp_path_factory.mktemp("marker-out") / "clean"
    result = run_cli(
        "export", str(source / "draft.tex"), "--output-dir", str(out), "--copy", "notes.txt",
        "--no-compile", "--private-marker", "/home/hexu/private-dataset",
    )
    assert result.returncode == 2
    assert "notes.txt:1" in result.stderr
    # without the marker the same export is clean
    out2 = tmp_path_factory.mktemp("marker-out2") / "clean"
    result = run_cli(
        "export", str(source / "draft.tex"), "--output-dir", str(out2), "--copy", "notes.txt", "--no-compile"
    )
    assert result.returncode == 0, result.stderr


